"""gen_shaders.py: assembles the renderer's own shaders, renderer/shaders/*.spvasm (spirv-as, checked with spirv-val),
and writes renderer/shaders/udr_shaders_spv.h with the SPIR-V embedded (used by udr_prod.c).
Needs SPIRV-Tools. Usage: python3 renderer/tests/gen_shaders.py"""
import glob, os, struct, subprocess, tempfile
d = os.path.dirname(os.path.abspath(__file__))
sub, header = '../shaders', '../shaders/udr_shaders_spv.h'
out = ['/* generated by tests/gen_shaders.py from the files in tests/%s - do not edit */' % sub]
with tempfile.TemporaryDirectory() as tmp:
    for f in sorted(glob.glob(os.path.join(d, sub, '*.spvasm'))):
        nm = os.path.basename(f)[:-7]
        spv = os.path.join(tmp, nm + '.spv')
        subprocess.check_call(['spirv-as', '--target-env', 'vulkan1.1', f, '-o', spv])
        subprocess.check_call(['spirv-val', '--target-env', 'vulkan1.1', spv])
        w = struct.unpack(f'<{os.path.getsize(spv) // 4}I', open(spv, 'rb').read())
        out.append(f'static const unsigned int spv_{nm}[{len(w)}] = {{' + ','.join(f'0x{x:08x}' for x in w) + '};')
open(os.path.join(d, header), 'w').write('\n'.join(out) + '\n')
print('ok', len(out) - 1, 'shaders ->', header)
