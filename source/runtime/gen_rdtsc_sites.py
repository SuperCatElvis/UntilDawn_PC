#!/usr/bin/env python3
"""Find every RDTSC (0F 31) inside a function of the eboot and plan a detour for it.

Why: the game reads the CPU time-stamp counter directly and converts it with a hard-coded 1.594 GHz
(the PS4's TSC rate; e.g. seconds * 1.594e9 -> ticks, 1.594e9 / ticks -> rate). A PC's TSC runs at its
own rate (3.187 GHz on the test machine), so every game timer ran twice as fast. Each RDTSC becomes a
jump to a native stub that returns a counter scaled to the PS4 rate.

Plan per site (like gen_extrq_sites.py): the 2-byte RDTSC plus the following whole instruction(s)
needed to free 5 bytes for 'jmp rel32'. Displaced instructions are copied into the stub, so they must be
position-independent: no RIP-relative operand, no branch/call/ret. One exception is supported: a direct
'jmp' / 'jcc' / 'call' as the last displaced instruction is re-encoded with a rel32 target in the stub.
No direct branch in the function may target the inside of the patched range.

Usage: python gen_rdtsc_sites.py <eboot.elf> <functions.csv> <out.h> <symbol_prefix>"""
import sys, os, re, csv, bisect
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))
from ps4_xref import Image
elf, fcsv, outp, pfx = sys.argv[1:5]
img = Image(elf, None)
F = [(int(r['start_va'], 16), int(r['end_va'], 16)) for r in csv.DictReader(open(fcsv))]
t = img.text; d = img.d
base_off = t['p_offset'] - t['p_vaddr']
code = d[t['p_offset']:t['p_offset'] + max(e for s, e in F)]
S = [f[0] for f in F]
cands = {}
for m in re.finditer(rb'\x0f\x31', code):
    i = bisect.bisect_right(S, m.start()) - 1
    if i >= 0 and F[i][0] <= m.start() < F[i][1]: cands.setdefault(F[i], []).append(m.start())

JCC = {'jo': 0, 'jno': 1, 'jb': 2, 'jae': 3, 'je': 4, 'jne': 5, 'jbe': 6, 'ja': 7, 'js': 8, 'jns': 9,
       'jp': 10, 'jnp': 11, 'jl': 12, 'jge': 13, 'jle': 14, 'jg': 15}
sites = []; bad = []; traps = []; nfun = 0
for f in sorted(cands):
    nfun += 1
    L = []
    for ln in img.disasm(f[0], f[1]).splitlines():
        m = re.match(r'\s*([0-9a-f]+):\t([0-9a-f ]+?)\s*\t(.*)$', ln)
        if m: L.append((int(m.group(1), 16), len(m.group(2).split()), m.group(3).strip())); continue
        m = re.match(r'\s*([0-9a-f]+):\t([0-9a-f ]+?)\s*$', ln)   # continuation line: the rest of a long encoding
        if m: L.append((int(m.group(1), 16), len(m.group(2).split()), ''))
    # objdump splits long encodings over two lines (continuation lines have no mnemonic): merge them
    M = []
    for a, n, ins in L:
        if M and ins == '' : M[-1] = (M[-1][0], M[-1][1] + n, M[-1][2]); continue
        M.append((a, n, ins))
    L = M
    starts = {a for a, n, ins in L}
    targets = set()
    for a, n, ins in L:
        mm = re.match(r'(j\w+|call|loop\w*)\s+0x([0-9a-f]+)', ins)
        if mm: targets.add(int(mm.group(2), 16))
    covered_until = 0
    for k, (a, n, ins) in enumerate(L):
        if not ins.startswith('rdtsc'): continue
        if a < covered_until: continue   # inside the previous site's patch: its stub reads the scaled clock for it (mask)
        cover = n; j = k + 1; br = None; ok = True; mask = 0
        while cover < 5:
            if j >= len(L): ok = False; bad.append((a, 'function ends')); traps.append(a); break
            a2, n2, ins2 = L[j]
            mm = re.match(r'(j\w+|call)\s+0x([0-9a-f]+)', ins2)
            if mm and (mm.group(1) in JCC or mm.group(1) in ('jmp', 'call')):
                br = (mm.group(1), int(mm.group(2), 16)); cover += n2; j += 1; break
            if 'rip' in ins2 or re.match(r'(j\w+|call|ret|loop|jrcxz|(bad)|int|ud2|syscall)', ins2) or 'fs:' in ins2 or 'gs:' in ins2:
                ok = False; bad.append((a, 'displaced instruction not relocatable: ' + ins2)); traps.append(a); break
            if ins2.startswith('rdtsc'): mask |= 1 << cover   # a second RDTSC among the displaced instructions
            cover += n2; j += 1
        if ok and cover < 5: ok = False; bad.append((a, 'only %d bytes before a branch' % cover)); traps.append(a)
        if not ok: continue
        inner = [x for x in targets if a < x < a + cover]
        if inner: bad.append((a, 'branch target inside patch range %s' % [hex(x) for x in inner])); traps.append(a); continue
        if br and br[0] == 'call' and False: pass
        # displaced bytes (without the trailing branch, which is re-encoded)
        blen = L[j - 1][1] if br else 0
        kind = 0; cc = 0; tgt = 0
        if br:
            kind = 1 if br[0] == 'jmp' else 2 if br[0] == 'call' else 3
            cc = JCC.get(br[0], 0); tgt = br[1]
        sites.append((a, cover, cover - blen, kind, cc, tgt, mask)); covered_until = a + cover
with open(outp, 'w') as fo:
    fo.write('/* generated by gen_rdtsc_sites.py from %s: %d RDTSC sites in %d functions */\n' % (os.path.basename(elf), len(sites), nfun))
    fo.write('/* va: the RDTSC; cover: bytes replaced; plain: bytes copied to the stub (RDTSC included);\n'
             '   br: 0 none, 1 jmp, 2 call, 3 jcc (cc = condition code), re-encoded to target va "to" */\n')
    fo.write('/* rd: bit i set = the displaced instruction at byte offset i is another RDTSC (the stub reads the scaled clock there too) */\n')
    fo.write('static const RdtscSite %s_rdtsc_sites[] = {\n' % pfx)
    for a, c, p, k, cc, tg, mk in sites: fo.write('  {%#x, %d, %d, %d, %d, %#x, %#x},\n' % (a, c, p, k, cc, tg, mk))
    fo.write('  {0, 0, 0, 0, 0, 0, 0}};\n')
    fo.write('/* RDTSC sites that cannot take a 5-byte jump (a branch lands right after them): made a 2-byte UD2,\n'
             '   emulated by the illegal-instruction handler */\n')
    fo.write('static const u32 %s_rdtsc_traps[] = {' % pfx + ''.join('%#x, ' % a for a in sorted(traps)) + '0};\n')
spans = sorted([(x[0], x[0] + x[1]) for x in sites] + [(t, t + 2) for t in traps])
for (a0, e0), (a1, e1) in zip(spans, spans[1:]):
    assert e0 <= a1, 'overlapping patches at %#x and %#x' % (a0, a1)
print('functions', nfun, 'sites', len(sites), 'problems', len(bad), 'with extra RDTSC in the stub', sum(1 for x in sites if x[6]))
from collections import Counter
print(Counter(b[1].split(':')[0] for b in bad))
for b in bad[:25]: print('  ', hex(b[0]), b[1])
