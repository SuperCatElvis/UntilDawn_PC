/* vote_borrow_test.c - t104: checks the wave-vote modes of gcn2spv's E6 compute translation on the CPU (spvi.c).
 * A hand-encoded GCN compute program with 64 lanes and the full 32 KB of LDS keeps a value in the LAST LDS dword
 * across a wave-level branch (s_cbranch_execz after s_and_saveexec: a workgroup vote in the translation), plus a
 * value per lane in the first dwords, and stores what it reads back. Expected for every lane: last dword 0x5555,
 * own dword tid + 1000, and for lanes < 32 the neighbour's dword (tid + 1001) read inside the branch.
 * Modes: slots (max_shared 0, the vote's own 3 workgroup dwords) and borrow (max_shared 32768, the vote in the last
 * LDS dword); the second must give the same results with workgroup memory of exactly 32768 bytes.
 * Build: gcc -O1 -w -I.. -o /tmp/vote_borrow_test vote_borrow_test.c ../spvi.c ../gcn2spv.c -lm */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "gcn2spv.h"
#include "spvi.h"
#include "gcn_ops_ci.h"   /* opcode names (generated by gen_gcn_ops.py) */
#define gcn_ops_sop1 g_names_SOP1
#define gcn_ops_sop2 g_names_SOP2
#define gcn_ops_sopp g_names_SOPP
#define gcn_ops_vop1 g_names_VOP1
#define gcn_ops_vop2 g_names_VOP2
#define gcn_ops_vopc g_names_VOPC
#define gcn_ops_ds g_names_DS
#define gcn_ops_mubuf g_names_MUBUF
#define GCN_OPS_SOP1_N (int)(sizeof g_names_SOP1 / sizeof g_names_SOP1[0])
#define GCN_OPS_SOP2_N (int)(sizeof g_names_SOP2 / sizeof g_names_SOP2[0])
#define GCN_OPS_SOPP_N (int)(sizeof g_names_SOPP / sizeof g_names_SOPP[0])
#define GCN_OPS_VOP1_N (int)(sizeof g_names_VOP1 / sizeof g_names_VOP1[0])
#define GCN_OPS_VOP2_N (int)(sizeof g_names_VOP2 / sizeof g_names_VOP2[0])
#define GCN_OPS_VOPC_N (int)(sizeof g_names_VOPC / sizeof g_names_VOPC[0])
#define GCN_OPS_DS_N (int)(sizeof g_names_DS / sizeof g_names_DS[0])
#define GCN_OPS_MUBUF_N (int)(sizeof g_names_MUBUF / sizeof g_names_MUBUF[0])

static unsigned opn(const char *const *t, int n, const char *name) {
    for (int i = 0; i < n; i++) if (t[i] && !strcmp(t[i], name)) return (unsigned)i;
    printf("no opcode %s\n", name); exit(2);
}
static unsigned sop1(const char *n, unsigned sd, unsigned s0) { return (0x17Du << 23) | (sd << 16) | (opn(gcn_ops_sop1, GCN_OPS_SOP1_N, n) << 8) | s0; }
static unsigned sop2(const char *n, unsigned sd, unsigned s0, unsigned s1) { return (2u << 30) | (opn(gcn_ops_sop2, GCN_OPS_SOP2_N, n) << 23) | (sd << 16) | (s1 << 8) | s0; }
static unsigned sopp(const char *n, int imm) { return (0x17Fu << 23) | (opn(gcn_ops_sopp, GCN_OPS_SOPP_N, n) << 16) | ((unsigned)imm & 0xFFFF); }
static unsigned vop1(const char *n, unsigned vd, unsigned s0) { return (0x3Fu << 25) | (vd << 17) | (opn(gcn_ops_vop1, GCN_OPS_VOP1_N, n) << 9) | s0; }
static unsigned vop2(const char *n, unsigned vd, unsigned s0, unsigned vs1) { return (opn(gcn_ops_vop2, GCN_OPS_VOP2_N, n) << 25) | (vd << 17) | (vs1 << 9) | s0; }
static unsigned vopc(const char *n, unsigned s0, unsigned vs1) { return (0x3Eu << 25) | (opn(gcn_ops_vopc, GCN_OPS_VOPC_N, n) << 17) | (vs1 << 9) | s0; }
static void ds(unsigned *w, const char *n, unsigned off, unsigned addr, unsigned d0, unsigned vdst) {
    w[0] = (0x36u << 26) | (opn(gcn_ops_ds, GCN_OPS_DS_N, n) << 18) | (off & 0xFFFF);
    w[1] = (vdst << 24) | (d0 << 8) | addr;
}
static void mubuf(unsigned *w, const char *n, unsigned off, int offen, unsigned vaddr, unsigned vdata, unsigned srsrc) {
    w[0] = (0x38u << 26) | (opn(gcn_ops_mubuf, GCN_OPS_MUBUF_N, n) << 18) | ((unsigned)offen << 12) | off;
    w[1] = (128u << 24) | ((srsrc / 4) << 16) | (vdata << 8) | vaddr;
}
#define V(n) (256u + (n))
#define LIT 255u
#define C(n) (128u + (n))
#define VCC 106u
#define EXEC 126u

typedef struct { u64 lo, size; u8 *h; } Reg;
static Reg R[4]; static int NR;
static u8 *ptm; static u64 pt_bytes;
static u8 rtab[16 + 64 * 32];
static u8 *reg_add(u64 lo, u64 size) { u8 *h = calloc(1, size); R[NR].lo = lo; R[NR].size = size; R[NR].h = h; NR++;
    for (u64 a = lo; a < lo + size; a += 0x10000) ((u64 *)ptm)[(a - G2S_PT_BASE) >> 16] = (u64)(uintptr_t)(h + (a - lo));
    return h; }
static u8 *guest(u64 a, u64 n) { for (int i = 0; i < NR; i++) if (a >= R[i].lo && a + n <= R[i].lo + R[i].size) return R[i].h + (a - R[i].lo); return 0; }
static int rd(void *ctx, u64 a, u32 *out, u32 n) { (void)ctx; u8 *p = guest(a, 4ull * n); if (!p) { memset(out, 0, 4ull * n); return 0; } memcpy(out, p, 4ull * n); return 1; }
static void *dev_ptr(void *ctx, u64 a, u32 n) {
    (void)ctx; u8 *p = (u8 *)(uintptr_t)a;
    for (int i = 0; i < NR; i++) if (p >= R[i].h && p + n <= R[i].h + R[i].size) return p;
    if (p >= ptm && p + n <= ptm + pt_bytes) return p;
    if (p >= rtab && p + n <= rtab + sizeof rtab) return p;
    return 0;
}
enum { CODE = 0x243000000ull, OUTB = 0x243040000ull };

static int run(u32 max_shared, const char *label, int *wg_bytes_out) {
    NR = 0; memset(rtab, 0, sizeof rtab); memset(ptm, 0, pt_bytes);
    u8 *code = reg_add(CODE, 0x10000), *outb = reg_add(OUTB, 0x10000);
    unsigned w[64]; int k = 0;
    w[k++] = vop2("V_LSHLREV_B32", 1, C(2), 0);                     /* v1 = tid * 4 */
    w[k++] = vop2("V_ADD_I32", 2, LIT, 0); w[k++] = 1000;           /* v2 = tid + 1000 */
    ds(&w[k], "DS_WRITE_B32", 0, 1, 2, 0); k += 2;                   /* LDS[tid] = tid + 1000 */
    w[k++] = vop1("V_MOV_B32", 3, LIT); w[k++] = 32764;              /* v3 = byte address of the last LDS dword */
    w[k++] = vop1("V_MOV_B32", 4, LIT); w[k++] = 0x5555;
    ds(&w[k], "DS_WRITE_B32", 0, 3, 4, 0); k += 2;                   /* LDS[8191] = 0x5555 */
    w[k++] = sopp("S_WAITCNT", 0); w[k++] = sopp("S_BARRIER", 0);
    w[k++] = vopc("V_CMP_GT_U32", C(32), 0);                         /* vcc = 32 > tid */
    w[k++] = sop1("S_AND_SAVEEXEC_B64", 4, VCC);
    int br = k; w[k++] = 0;                                          /* s_cbranch_execz L (patched) */
    ds(&w[k], "DS_READ_B32", 4, 1, 0, 5); k += 2;                    /* v5 = LDS[tid + 1] */
    w[k++] = sopp("S_WAITCNT", 0);
    ds(&w[k], "DS_WRITE_B32", 256, 1, 5, 0); k += 2;                 /* LDS[64 + tid] = v5 (an LDS write in the branch: the translation votes) */
    int L = k; w[br] = sopp("S_CBRANCH_EXECZ", L - (br + 1));
    w[k++] = sop2("S_OR_B64", EXEC, EXEC, 4);
    ds(&w[k], "DS_READ_B32", 0, 3, 0, 6); k += 2;                    /* v6 = LDS[8191] */
    ds(&w[k], "DS_READ_B32", 0, 1, 0, 7); k += 2;                    /* v7 = LDS[tid] */
    ds(&w[k], "DS_READ_B32", 256, 1, 0, 9); k += 2;                  /* v9 = LDS[64 + tid] */
    w[k++] = sopp("S_WAITCNT", 0);
    w[k++] = vop2("V_LSHLREV_B32", 8, C(4), 0);                      /* v8 = tid * 16 */
    unsigned m[2];
    mubuf(m, "BUFFER_STORE_DWORD", 0, 1, 8, 6, 0); w[k++] = m[0]; w[k++] = m[1];
    mubuf(m, "BUFFER_STORE_DWORD", 4, 1, 8, 7, 0); w[k++] = m[0]; w[k++] = m[1];
    mubuf(m, "BUFFER_STORE_DWORD", 8, 1, 8, 5, 0); w[k++] = m[0]; w[k++] = m[1];
    mubuf(m, "BUFFER_STORE_DWORD", 12, 1, 8, 9, 0); w[k++] = m[0]; w[k++] = m[1];
    w[k++] = sopp("S_ENDPGM", 0);
    memcpy(code, w, 4ull * k);
    u32 ud[16] = {(u32)OUTB, (u32)(OUTB >> 32), 0x10000, 0x00024FAC};
    *(u32 *)rtab = (u32)NR; *(u64 *)(rtab + 8) = (u64)(uintptr_t)ptm;
    for (int i = 0; i < NR; i++) { u64 *e = (u64 *)(rtab + 16 + 32 * i); e[0] = R[i].lo; e[1] = R[i].lo + R[i].size; e[2] = (u64)(uintptr_t)R[i].h; }
    G2SIn in; memset(&in, 0, sizeof in);
    in.stage = G2S_CS; in.code_addr = CODE; in.read = rd; in.n_user = 4;
    in.rsrc1 = 0x42; in.rsrc2 = (64u << 15) | (4u << 1);   /* LDS 64 x 512 bytes = 32 KB, 4 user SGPRs */
    in.cs_threads[0] = 64; in.cs_threads[1] = 1; in.cs_threads[2] = 1; in.tex_binding_base = 1;
    for (int i = 0; i < 16; i++) in.user_data[i] = ud[i];
    in.max_shared = max_shared;
    G2SOut out;
    if (!g2s_translate(&in, &out)) { printf("%s: translate failed: %s\n", label, out.err); return 0; }
    /* workgroup memory declared by the module: sum of the Workgroup OpVariables' array sizes (u32 arrays only here) */
    int wg = 0;
    { const u32 *s = out.spv; u32 n = out.n; u32 cval[65536] = {0}; static u32 arrlen[65536], ptrarr[65536];
      memset(arrlen, 0, sizeof arrlen); memset(ptrarr, 0, sizeof ptrarr);
      for (u32 i = 5; i < n; ) { u32 op = s[i] & 0xFFFF, len = s[i] >> 16; if (!len) break;
          if (op == 43 && s[i + 2] < 65536) cval[s[i + 2]] = s[i + 3];                       /* OpConstant */
          if (op == 28 && s[i + 1] < 65536) arrlen[s[i + 1]] = cval[s[i + 3]];               /* OpTypeArray */
          if (op == 32 && s[i + 1] < 65536 && s[i + 2] == 4) ptrarr[s[i + 1]] = s[i + 3];      /* OpTypePointer Workgroup */
          if (op == 59 && s[i + 3] == 4 && s[i + 1] < 65536) wg += 4 * (int)arrlen[ptrarr[s[i + 1]]];   /* OpVariable Workgroup */
          i += len; } }
    *wg_bytes_out = wg;
    enum { NL = 64 };
    static SpvEnv env[NL]; SpvModule *mm[NL]; char err[256]; static u8 shared[1 << 16];
    for (int l = 0; l < NL; l++) { mm[l] = spvi_load(out.spv, out.n, err, sizeof err); if (!mm[l]) { printf("%s: spvi_load: %s\n", label, err); return 0; } }
    memset(shared, 0xCD, sizeof shared);
    int st[NL];
    for (int l = 0; l < NL; l++) { SpvEnv *e = &env[l]; memset(e, 0, sizeof *e);
        e->dev_ptr = dev_ptr; e->binding[0] = rtab; memcpy(e->push, ud, 64);
        e->local_id[0] = (u32)l; e->local_index = (u32)l; e->num_workgroups[0] = e->num_workgroups[1] = e->num_workgroups[2] = 1;
        e->workgroup = shared; e->workgroup_bytes = sizeof shared; e->max_steps = 100000000ull;
        st[l] = spvi_start(mm[l], e, err, sizeof err); if (!st[l]) { printf("%s: lane %d: %s\n", label, l, err); return 0; } }
    for (;;) { int waiting = 0; for (int l = 0; l < NL; l++) if (st[l] == 2) waiting++;
        if (!waiting) break;
        for (int l = 0; l < NL; l++) { st[l] = spvi_resume(mm[l]); if (!st[l]) { printf("%s: resume failed\n", label); return 0; } } }
    int bad = 0; const u32 *o = (const u32 *)outb;
    for (int t = 0; t < 64; t++) {
        u32 last = o[4 * t], own = o[4 * t + 1], nb = o[4 * t + 2], wr = o[4 * t + 3];
        int ok = last == 0x5555 && own == (u32)t + 1000 && (t >= 32 || (nb == (u32)t + 1001 && wr == (u32)t + 1001));
        if (!ok) { if (bad < 6) printf("  %s lane %2d: last %#x own %u neighbour %u\n", label, t, last, own, nb); bad++; }
    }
    printf("%s: %d of 64 lanes wrong, workgroup memory declared %d bytes, %u barriers\n", label, bad, wg, spvi_barriers(mm[0]));
    return bad == 0;
}
int main(void) {
    pt_bytes = (G2S_PT_SIZE >> 16) * 8; ptm = calloc(1, pt_bytes);
    int wa = 0, wb = 0;
    int a = run(0, "slots ", &wa), b = run(32768, "borrow", &wb);
    int ok = a && b && wa == 32768 + 12 && wb == 32768;
    printf("RESULT: %s\n", ok ? "PASS" : "FAIL");
    return ok ? 0 : 1;
}
