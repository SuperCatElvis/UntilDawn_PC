"""gen_rsqrt_sites.py - rsqrt_sites.h (t149, diagnostic --rsqrt-trap): every 128-bit [v]rsqrtps/ss in eboot and all_programs.prx.
Usage: python3 gen_rsqrt_sites.py <eboot objdump -d output> <all_programs objdump -d output> <out.h> <eboot.functions_ehframe.csv> <all_programs.functions_ehframe.csv>
(the CSVs from tools/ps4_ehframe.py; each objdump output from: objdump -D -b binary -m i386:x86-64 -M intel <file.elf>,
the plain ELFs made with tools/fself_unpack.py)."""
import csv, sys, re, bisect
def load(dis, fcsv):
    fr = sorted((int(r['start_va'],16), int(r['end_va'],16)) for r in csv.DictReader(open(fcsv)))
    starts = [a for a, b in fr]
    out = []
    for l in open(dis):
        if 'rsqrt' not in l: continue
        m = re.match(r'\s*([0-9a-f]+):\s+((?:[0-9a-f]{2} )+)\s*(\S+)\s+(.*)', l)
        if not m: continue
        fo = int(m.group(1), 16); va = fo - 0x4000; byts = m.group(2).split(); mn = m.group(3); ops = m.group(4)
        i = bisect.bisect_right(starts, va) - 1
        if i < 0 or not (fr[i][0] <= va < fr[i][1]): continue
        if 'ymm' in ops: continue
        out.append((va, len(byts), mn, ''.join(byts), ops.strip()))
    return out
e = load(sys.argv[1], sys.argv[4])
p = load(sys.argv[2], sys.argv[5])
import collections
print(len(e), len(p), collections.Counter(x[2] for x in e + p))
with open(sys.argv[3], 'w') as f:
    f.write('/* rsqrt_sites.h (t149, generated by gen_rsqrt_sites.py from the eh_frame function ranges): every [v]rsqrtps / [v]rsqrtss (128-bit) in eboot (module 0) and all_programs.prx (module 1): offset, length, first two bytes */\n')
    f.write('static const struct { u32 off; u8 mod, len; u16 b01; } g_rsq_sites[] = {\n')
    for mod, L in ((0, e), (1, p)):
        for va, n, mn, b, ops in L:
            f.write('  {0x%x, %d, %d, 0x%s},\n' % (va, mod, n, b[2:4] + b[0:2]))
    f.write('};\n')
