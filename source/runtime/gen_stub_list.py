#!/usr/bin/env python3
"""gen_stub_list.py - writes e3_stub_list.h: STUB_LIST(X) = X(0) X(1) ... X(n-1) (one stub function per import slot).
Usage: python3 gen_stub_list.py [n=1024] > e3_stub_list.h"""
import sys
n = int(sys.argv[1]) if len(sys.argv) > 1 else 1024
print('/* generated by gen_stub_list.py - do not edit */')
print('#define STUB_LIST(X) ' + ' '.join('X(%d)' % i for i in range(n)))
