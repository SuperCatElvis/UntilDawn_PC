#!/usr/bin/env python3
"""Find every SSE4a EXTRQ (register form) in the eboot and plan a trap-free detour:
the EXTRQ plus the following whole instruction(s) needed to free 5 bytes for a 'jmp rel32'.
Displaced instructions must be position-independent (no RIP-relative operand, no branch),
and no branch in the containing function may target the inside of the patched range.
Usage: python gen_extrq_sites.py <eboot.elf> <functions.csv> <out.h> <symbol_prefix> [--no-typedef]
(functions.csv: tools/ps4_ehframe.py <eboot.elf> <functions.csv>; --no-typedef for a second table in the same file,
as e3_extrq_v100.h next to e3_extrq_v103.h)"""
import sys, os, re, csv, bisect
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))
from ps4_xref import Image
elf, fcsv, outp, pfx = sys.argv[1:5]
img = Image(elf, None)
F = [(int(r['start_va'], 16), int(r['end_va'], 16)) for r in csv.DictReader(open(fcsv))]
t = img.text; d = img.d
code = d[t['p_offset']:t['p_offset'] + max(e for s, e in F)]
S = [f[0] for f in F]
cands = set()
for m in re.finditer(rb'\x66[\x40-\x4f]?\x0f\x79', code):
    i = bisect.bisect_right(S, m.start()) - 1
    if i >= 0 and F[i][0] <= m.start() < F[i][1]: cands.add(F[i])
sites = []; bad = []
for f in sorted(cands):
    L = []
    for ln in img.disasm(f[0], f[1]).splitlines():
        m = re.match(r'\s*([0-9a-f]+):\t([0-9a-f ]+?)\s*\t(.*)$', ln)
        if m: L.append((int(m.group(1), 16), len(m.group(2).split()), m.group(3))); continue
        m = re.match(r'\s*([0-9a-f]+):\t([0-9a-f ]+?)\s*$', ln)   # continuation line of a long (8+ byte) encoding
        if m and L: L[-1] = (L[-1][0], L[-1][1] + len(m.group(2).split()), L[-1][2])
    targets = set()
    for a, n, ins in L:
        mm = re.match(r'(j\w+|call)\s+0x([0-9a-f]+)', ins)
        if mm: targets.add(int(mm.group(2), 16))
    if any(re.match(r'jmp\s+(r|QWORD)', ins) for a, n, ins in L): bad.append((f[0], 'indirect jump in function'))
    for k, (a, n, ins) in enumerate(L):
        if not ins.startswith('extrq'): continue
        cover = n; j = k + 1
        while cover < 5:
            a2, n2, ins2 = L[j]
            if 'rip' in ins2 or re.match(r'(j\w+|call|ret|loop)', ins2) or '(bad)' in ins2:
                bad.append((a, 'displaced instruction not relocatable: ' + ins2)); break
            cover += n2; j += 1
        inner = [x for x in targets if a < x < a + cover]
        if inner: bad.append((a, 'branch target inside patch range %s' % [hex(x) for x in inner]))
        b = d[t['p_offset'] + a: t['p_offset'] + a + n]
        rex = b[1] if (b[1] & 0xF0) == 0x40 else 0
        modrm = b[-1]
        dst = ((modrm >> 3) & 7) | (8 if rex & 4 else 0)
        src = (modrm & 7) | (8 if rex & 1 else 0)
        sites.append((a, n, cover, dst, src))
sp = sorted((a, a + c) for a, n, c, ds, sr in sites)
for (a0, e0), (a1, e1) in zip(sp, sp[1:]): assert e0 <= a1, 'overlapping EXTRQ patches %#x %#x' % (a0, a1)
with open(outp, 'w') as fo:
    fo.write('/* generated by gen_extrq_sites.py from %s */\n' % os.path.basename(elf))
    if '--no-typedef' not in sys.argv[5:]: fo.write('typedef struct { u32 va; u8 len, cover, dst, src; } ExtrqSite;\n')
    fo.write('static const ExtrqSite %s_extrq_sites[] = {\n' % pfx)
    for a, n, c, ds, sr in sites: fo.write('  {%#x, %d, %d, %d, %d},\n' % (a, n, c, ds, sr))
    fo.write('  {0, 0, 0, 0, 0}};\n')
print('functions', [hex(f[0]) for f in sorted(cands)], 'sites', len(sites), 'problems', len(bad))
for b in bad[:10]: print('  ', hex(b[0]), b[1])
